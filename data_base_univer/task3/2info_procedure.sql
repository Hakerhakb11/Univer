CREATE OR REPLACE PROCEDURE сформировать_список_книг_на_руках()
LANGUAGE plpgsql
AS $$
BEGIN
    DROP TABLE IF EXISTS Список_книг_на_руках;

    CREATE TABLE Список_книг_на_руках AS
    SELECT 
        Книги.Название AS "Название книги",
        Читатели.ФИО AS "Читатель",
        Журнал_выдачи.Дата_выдачи AS "Дата выдачи",
        Журнал_выдачи.Ожидаемая_дата_возврата AS "Предполагаемая дата возврата"
    FROM Журнал_выдачи
    JOIN Читатели ON Журнал_выдачи.ID_Читателя = Читатели.ID_Читателя
    JOIN Издания ON Журнал_выдачи.ID_Издания = Издания.ID_Издания
    JOIN Авторы_и_Книги ON Издания.ID_Автора_и_Книги = Авторы_и_Книги.ID_Автора_и_Книги
    JOIN Книги ON Авторы_и_Книги.ID_Книги = Книги.ID_Книги
    WHERE Журнал_выдачи.ID_Выдачи NOT IN (
        SELECT ID_Выдачи 
        FROM Журнал_сдачи
    )
    ORDER BY Журнал_выдачи.Ожидаемая_дата_возврата ASC;

    RAISE NOTICE 'Список книг на руках успешно сформирован в таблице Список_книг_на_руках.';
END;
$$;