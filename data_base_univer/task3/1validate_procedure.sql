CREATE OR REPLACE PROCEDURE проверить_возврат_и_начислить_штраф(p_id_сдачи INT)
LANGUAGE plpgsql
AS $$
DECLARE
    v_дата_выдачи DATE;
    v_ожидаемая_дата DATE;
    v_фактическая_дата DATE;
    v_дни_просрочки INT;
    v_ставка_в_день NUMERIC(10, 2);
    v_id_штрафа INT;
    v_сумма_штрафа NUMERIC(10, 2);
BEGIN
    SELECT 
        Журнал_выдачи.Дата_выдачи,
        Журнал_выдачи.Ожидаемая_дата_возврата,
        Журнал_сдачи.Фактическая_дата_возврата
    INTO 
        v_дата_выдачи,
        v_ожидаемая_дата,
        v_фактическая_дата
    FROM Журнал_сдачи
    JOIN Журнал_выдачи ON Журнал_сдачи.ID_Выдачи = Журнал_выдачи.ID_Выдачи
    WHERE Журнал_сдачи.ID_Сдачи = p_id_сдачи;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Запись о сдаче с ID % не найдена в базе!', p_id_сдачи;
    END IF;

    IF v_фактическая_дата < v_дата_выдачи THEN
        RAISE EXCEPTION 'Ошибка даты: фактическая сдача (%) не может быть раньше выдачи книги (%)!', 
            v_фактическая_дата, v_дата_выдачи;
    END IF;

    IF v_фактическая_дата > v_ожидаемая_дата THEN
        v_дни_просрочки := v_фактическая_дата - v_ожидаемая_дата;

        SELECT ID_Штрафа, Цена
        INTO v_id_штрафа, v_ставка_в_день
        FROM Типы_штрафов
        WHERE ID_Штрафа = 1
        LIMIT 1;

        v_сумма_штрафа := v_дни_просрочки * v_ставка_в_день;

        INSERT INTO Штрафы (ID_Сдачи, ID_Штрафа, Сумма_штрафа)
        VALUES (p_id_сдачи, v_id_штрафа, v_сумма_штрафа)
        ON CONFLICT (ID_Сдачи, ID_Штрафа) 
        DO UPDATE SET Сумма_штрафа = v_сумма_штрафа;

        RAISE NOTICE 'Сдача ID %: зафиксирована просрочка на % дн. Начислен штраф: % руб.', 
            p_id_сдачи, v_дни_просрочки, v_сумма_штрафа;
    ELSE
        RAISE NOTICE 'Сдача ID %: книга возвращена вовремя. Штрафа нет.', p_id_сдачи;
    END IF;
END;
$$;