SELECT 
    Книги.Название AS "Название книги",
    COUNT(Журнал_выдачи.ID_Выдачи) AS "Количество выдач"
FROM Журнал_выдачи
JOIN Издания ON Журнал_выдачи.ID_Издания = Издания.ID_Издания
JOIN Авторы_и_Книги ON Издания.ID_Автора_и_Книги = Авторы_и_Книги.ID_Автора_и_Книги
JOIN Книги ON Авторы_и_Книги.ID_Книги = Книги.ID_Книги
WHERE (EXTRACT(YEAR FROM CURRENT_DATE) - Издания.Год_издания) > 10
GROUP BY Книги.ID_Книги, Книги.Название
HAVING COUNT(Журнал_выдачи.ID_Выдачи) >= 0.8 * (
    SELECT COUNT(Журнал_выдачи.ID_Выдачи)
    FROM Журнал_выдачи
    JOIN Издания ON Журнал_выдачи.ID_Издания = Издания.ID_Издания
    JOIN Авторы_и_Книги ON Издания.ID_Автора_и_Книги = Авторы_и_Книги.ID_Автора_и_Книги
    WHERE (EXTRACT(YEAR FROM CURRENT_DATE) - Издания.Год_издания) > 10
    GROUP BY Авторы_и_Книги.ID_Книги
    ORDER BY COUNT(Журнал_выдачи.ID_Выдачи) DESC
    LIMIT 1
)
ORDER BY "Количество выдач" DESC;
