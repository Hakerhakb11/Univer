SELECT
    Книги.Название AS "Название книги",
    Авторы.ФИО AS "Автор",
    Жанры.Название AS "Жанр",
    Серии.Название AS "Серия",
    Издательства.Название AS "Издательство",
    Издания.Год_издания AS "Год издания",
    Издания.Цена AS "Цена"
FROM Издания
JOIN Серии ON Издания.ID_Серии = Серии.ID_Серии
JOIN Издательства ON Серии.ID_Издательства = Издательства.ID_Издательства
JOIN Авторы_и_Книги ON Издания.ID_Автора_и_Книги = Авторы_и_Книги.ID_Автора_и_Книги
JOIN Книги ON Авторы_и_Книги.ID_Книги = Книги.ID_Книги
JOIN Жанры ON Книги.ID_Жанра = Жанры.ID_Жанра
JOIN Авторы ON Авторы_и_Книги.ID_Автора = Авторы.ID_Автора
WHERE Серии.Название = 'фантастика';