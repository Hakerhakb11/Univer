SELECT 
    Читатели.ФИО AS "ФИО читателя",
    Читатели.Телефон AS "Телефон"
FROM Читатели
    JOIN Журнал_выдачи ON Читатели.ID_Читателя = Журнал_выдачи.ID_Читателя
    WHERE (CURRENT_DATE - Журнал_выдачи.Ожидаемая_дата_возврата) > 10
        AND Журнал_выдачи.ID_Выдачи NOT IN (
            SELECT ID_Сдачи
            FROM Журнал_сдачи
        );
